import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createParser,publicState,candidates,latestLog} from '../src/power.mjs';
import {constrainActions} from '../src/policy.mjs';
import {prepare} from '../src/choose.mjs';
const root='runtime/ranked-2026-10-01T12-42-04-012Z';
const {resultOf,lastGameLog}=await import('../src/game-health.mjs');
const finalRaw=await readFile((await latestLog()).path,'utf8');
const raw=lastGameLog(finalRaw);
await writeFile(root+'/game-0022-full-Power.log',raw);
const defs=JSON.parse(await readFile('data/cards.enUS.json','utf8'));
const cards=Object.fromEntries(defs.map(c=>[c.id,c]));
const sent=raw.indexOf('GameState.SendChoices() - id=1');
const p=createParser().feed(raw.slice(0,raw.lastIndexOf('\n',sent)+1));
const before=publicState(p.result(),1,cards);
const options=constrainActions(before,candidates(p.result(),before));
const action=prepare(before,options).forced?.action??candidates(p.result(),before).find(a=>a.id==='m4');
