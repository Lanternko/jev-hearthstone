// Preserve the old stop-time artifact; append the subsequently available result separately.
const account=raw.match(/PlayerID=1, PlayerName=([^\r\n]+)/)?.[1]?.trim();
const result=resultOf(raw,account);
await writeFile(root+'/game-0022-post-stop-result.json',JSON.stringify({capturedAt:new Date().toISOString(),result,completedAfterRunnerStopped:true,gameNumber:22,modelDecisions:0,interrupted:true,excludeFromNormalStrategySample:true},null,2));
console.log(JSON.stringify({before:before.status,action,after:after.status,receipt:after.mulliganResult,postStopResult:result}));
